"""Tables (eval/results/tables.md) and learning-curve plots (eval/plots/) from run JSON.

Final return = mean episodic return over the last 10% of training steps (stochastic policy),
per seed; tables show the mean over 5 seeds with a 95% t-interval, and differences use Welch's
t-interval (runs with the same seed diverge after the first update, so they are not paired).
"""

from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from scipy import stats  # noqa: E402

RES = Path("eval/results")
ENVS = ["CartPole-v1", "Acrobot-v1", "Hopper-v5", "HalfCheetah-v5"]
STEPS = {"CartPole-v1": 500_000, "Acrobot-v1": 500_000, "Hopper-v5": 1_000_000,
         "HalfCheetah-v5": 1_000_000}
LABEL = {"full": "full PPO", "no_adv_norm": "− advantage normalisation",
         "no_value_clip": "− value-loss clipping", "no_obs_norm": "− observation normalisation",
         "no_reward_norm": "− reward scaling", "no_ortho_init": "− orthogonal init",
         "no_lr_anneal": "− LR annealing", "no_grad_clip": "− gradient clipping"}


def tci(xs: list[float]) -> tuple[float, float]:
    xs = [x for x in xs if np.isfinite(x)]
    mu = float(np.mean(xs))
    h = float(stats.t.ppf(0.975, len(xs) - 1) * np.std(xs, ddof=1) / math.sqrt(len(xs))) \
        if len(xs) > 1 else float("nan")
    return mu, h


def welch(a: list[float], b: list[float]) -> tuple[float, float, float]:
    a_, b_ = np.array(a), np.array(b)
    d = b_.mean() - a_.mean()
    va, vb = a_.var(ddof=1) / len(a_), b_.var(ddof=1) / len(b_)
    se = math.sqrt(va + vb)
    df = (va + vb) ** 2 / (va ** 2 / (len(a_) - 1) + vb ** 2 / (len(b_) - 1))
    p = float(stats.ttest_ind(b_, a_, equal_var=False).pvalue)
    return float(d), float(stats.t.ppf(0.975, df) * se), p


def curve(episodes: list, total: int, bins: int = 50) -> tuple[np.ndarray, np.ndarray]:
    e = np.array(episodes, dtype=float)
    edges = np.linspace(0, total, bins + 1)
    mids = (edges[:-1] + edges[1:]) / 2
    vals = np.array([e[(e[:, 0] > lo) & (e[:, 0] <= hi), 1].mean()
                     if ((e[:, 0] > lo) & (e[:, 0] <= hi)).any() else np.nan
                     for lo, hi in zip(edges[:-1], edges[1:], strict=True)])
    return mids, vals


def main() -> None:
    ours = defaultdict(list)
    for p in sorted((RES / "runs").glob("*.json")):
        r = json.loads(p.read_text())
        ours[(r["config"]["env_id"], r["config"]["tag"])].append(r)
    sb3 = defaultdict(list)
    for p in sorted((RES / "sb3").glob("*.json")):
        r = json.loads(p.read_text())
        sb3[r["env"]].append(r)
    out = ["# Results (generated by scripts/make_tables.py)\n",
           "## Full PPO vs Stable-Baselines3 PPO (matched hyperparameters), 5 seeds\n",
           "| env | steps | ours: final return | SB3: final return | Δ (ours − SB3), Welch 95% CI "
           "| p | ours wall min |", "|---|---|---|---|---|---|---|"]
    for env in ENVS:
        a = [r["final_return"] for r in ours.get((env, "full"), [])]
        b = [r["final_return"] for r in sb3.get(env, [])]
        if len(a) < 2:
            continue
        ma, ha = tci(a)
        cell_b, dcell, pcell = "-", "-", "-"
        if len(b) >= 2:
            mb, hb = tci(b)
            cell_b = f"{mb:.1f} ± {hb:.1f}"
            d, h, p = welch(b, a)
            dcell, pcell = f"{d:+.1f} ± {h:.1f}", f"{p:.2f}"
        wall = np.mean([r["wall_s"] for r in ours[(env, "full")]]) / 60
        out.append(f"| {env} | {STEPS[env]:,} | {ma:.1f} ± {ha:.1f} | {cell_b} | {dcell} | "
                   f"{pcell} | {wall:.1f} |")
    out.append("")
    for env in ("Hopper-v5", "CartPole-v1"):
        full = [r["final_return"] for r in ours.get((env, "full"), [])]
        full_auc = [r["auc_return"] for r in ours.get((env, "full"), [])]
        if len(full) < 2:
            continue
        out += [f"## Ablations on {env} (each removes one detail from full PPO), 5 seeds\n",
                "| variant | final return | Δ final vs full (95% CI) | p | p (Holm) | mean return "
                "over training (AUC) | Δ AUC vs full |", "|---|---|---|---|---|---|---|"]
        pvals = {}
        for tag in LABEL:
            rs = ours.get((env, tag), [])
            if tag != "full" and len(rs) >= 2:
                pvals[tag] = welch(full, [r["final_return"] for r in rs])[2]
        order = sorted(pvals, key=pvals.get)
        holm, running = {}, 0.0
        for i, tag in enumerate(order):
            running = max(running, min(1.0, (len(order) - i) * pvals[tag]))
            holm[tag] = running
        for tag in LABEL:
            rs = ours.get((env, tag), [])
            if len(rs) < 2:
                continue
            f = [r["final_return"] for r in rs]
            au = [r["auc_return"] for r in rs]
            mf, hf = tci(f)
            ma, ha = tci(au)
            if tag == "full":
                out.append(f"| {LABEL[tag]} | {mf:.1f} ± {hf:.1f} | - | - | - | "
                           f"{ma:.1f} ± {ha:.1f} "
                           "| - |")
                continue
            d, h, p = welch(full, f)
            da, hda, _ = welch(full_auc, au)
            out.append(f"| {LABEL[tag]} | {mf:.1f} ± {hf:.1f} | {d:+.1f} ± {h:.1f} | {p:.3f} | "
                       f"{holm[tag]:.3f} | {ma:.1f} ± {ha:.1f} | {da:+.1f} ± {hda:.1f} |")
        out.append("")
    (RES / "tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    Path("eval/plots").mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(1, 4, figsize=(14, 3))
    for ax, env in zip(axes, ENVS, strict=True):
        for runs, lab, col in ((ours.get((env, "full"), []), "ours", "#4C72B0"),
                               (sb3.get(env, []), "SB3", "#DD8452")):
            if not runs:
                continue
            cs = np.array([curve(r["episodes"], STEPS[env])[1] for r in runs])
            x = curve(runs[0]["episodes"], STEPS[env])[0]
            m = np.nanmean(cs, 0)
            s = np.nanstd(cs, 0) / np.sqrt(len(cs))
            ax.plot(x, m, color=col, label=lab)
            ax.fill_between(x, m - 1.96 * s, m + 1.96 * s, color=col, alpha=0.2)
        ax.set_title(env, fontsize=9)
        ax.set_xlabel("env steps")
        ax.ticklabel_format(axis="x", style="sci", scilimits=(0, 0))
        ax.spines[["top", "right"]].set_visible(False)
    axes[0].set_ylabel("episodic return")
    axes[0].legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig("eval/plots/curves_vs_sb3.png", dpi=150)
    plt.close(fig)
    fig, ax = plt.subplots(figsize=(6.5, 3.6))
    cmap = plt.get_cmap("tab10")
    for i, tag in enumerate(LABEL):
        runs = ours.get(("Hopper-v5", tag), [])
        if not runs:
            continue
        cs = np.array([curve(r["episodes"], STEPS["Hopper-v5"], 25)[1] for r in runs])
        x = curve(runs[0]["episodes"], STEPS["Hopper-v5"], 25)[0]
        ax.plot(x, np.nanmean(cs, 0), color="black" if tag == "full" else cmap(i),
                lw=2 if tag == "full" else 1, label=LABEL[tag])
    ax.set_xlabel("env steps")
    ax.set_ylabel("Hopper-v5 return (mean of 5 seeds)")
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(frameon=False, fontsize=7)
    fig.tight_layout()
    fig.savefig("eval/plots/hopper_ablations.png", dpi=150)
    plt.close(fig)


if __name__ == "__main__":
    main()
